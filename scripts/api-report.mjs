// The public API of `simple-liquid-glass/next` as one reviewed file: api/next.api.md is the built type
// declaration (dist/next.d.ts), so a change to what the entry exports is a diff in a pull request.
//   node scripts/api-report.mjs            fails when the built declaration differs from the report
//   node scripts/api-report.mjs --update   rewrites the report from the built declaration
// Run `npm run build` first: the report is made from dist.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';

const built = 'dist/next.d.ts';
const report = 'api/next.api.md';
if (!existsSync(built)) {
  console.error(`${built} is missing: run \`npm run build\` first.`);
  process.exit(1);
}
const declaration = readFileSync(built, 'utf8')
  .split('\n')
  .map((line) => line.trimEnd())
  .join('\n')
  .trim();
const text = [
  '# API report: `simple-liquid-glass/next`',
  '',
  'Generated by `npm run api:update` from the built type declaration. Do not edit by hand. `npm run api:check`',
  '(in CI and before publishing) fails when the entry exports something this file does not say. The',
  '`simple-liquid-glass/next/stack` entry has the same types; what only it implements is marked in the comments.',
  '',
  '```ts',
  declaration,
  '```',
  '',
].join('\n');

if (process.argv.includes('--update')) {
  mkdirSync('api', { recursive: true });
  writeFileSync(report, text);
  console.log(`${report} written.`);
} else if (!existsSync(report) || readFileSync(report, 'utf8') !== text) {
  console.error(
    `${report} is not what ${built} declares. Review the change, then run \`npm run api:update\`.`,
  );
  process.exit(1);
} else {
  console.log(`${report} matches ${built}.`);
}
